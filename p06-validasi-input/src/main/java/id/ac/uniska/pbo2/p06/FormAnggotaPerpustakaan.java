    private void txtNpmKeyTyped(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_txtNpmKeyTyped
    char karakter = evt.getKeyChar();

    if (!Character.isDigit(karakter)
        || txtNpm.getText().length() >= 10) {
    evt.consume();
}
    }//GEN-LAST:event_txtNpmKeyTyped

    private void txtEmailFocusLost(java.awt.event.FocusEvent evt) {//GEN-FIRST:event_txtEmailFocusLost
    String email = txtEmail.getText().trim();

    if (email.isEmpty()) {
    lblPesan.setText("Email harus diisi!");
    } else if (!email.matches("^[A-Za-z0-9+_.-]+@[A-Za-z0-9.-]+$")) {
    lblPesan.setText("Format email tidak valid!");
    } else {
    lblPesan.setText("");
}
    }//GEN-LAST:event_txtEmailFocusLost


    private void btnDaftarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDaftarActionPerformed
    String nama = txtNama.getText().trim();
    String npm = txtNpm.getText().trim();
    String email = txtEmail.getText().trim();
    String telepon = txtTelepon.getText().trim();

    if (nama.isEmpty() || npm.isEmpty()
        || email.isEmpty() || telepon.isEmpty()) {

    lblPesan.setText("Semua data harus diisi!");
    return;
}

    if (!npm.matches("\\d{10}")) {
    lblPesan.setText("NPM harus terdiri dari 10 digit angka!");
    txtNpm.requestFocusInWindow();
    return;
    
    
}
    if (!telepon.matches("\\d{10,13}")) {
    lblPesan.setText("Nomor telepon harus 10-13 digit angka!");
    txtTelepon.requestFocusInWindow();
    return;
}
    lblPesan.setText("Data berhasil divalidasi!");
    }//GEN-LAST:event_btnDaftarActionPerformed


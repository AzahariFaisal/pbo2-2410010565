    private void btnSimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSimpanActionPerformed
    String kode = txtKode.getText().trim();
String judul = txtJudul.getText().trim();

if (kode.isEmpty() || judul.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(
        this,
        "Kode Buku dan Judul Buku wajib diisi!",
        "Validasi",
        javax.swing.JOptionPane.WARNING_MESSAGE
    );
    return;
}
    int tahun;

try {
    tahun = Integer.parseInt(txtTahun.getText().trim());

    if (tahun < 1900 || tahun > 2026) {
        javax.swing.JOptionPane.showMessageDialog(
            this,
            "Tahun terbit harus antara 1900 dan 2026!",
            "Validasi Tahun",
            javax.swing.JOptionPane.WARNING_MESSAGE
        );
        return;
    }

} catch (NumberFormatException e) {
    javax.swing.JOptionPane.showMessageDialog(
        this,
        "Tahun terbit harus berupa angka!",
        "Validasi Tahun",
        javax.swing.JOptionPane.WARNING_MESSAGE
    );
    return;
    
    
}
    String penulis = txtPenulis.getText().trim();
   String status = cmbStatus.getSelectedItem().toString();

     buku = new Buku(
    kode,
    judul,
    penulis,
    tahun,
    status
);

berhasil = true;
dispose();
    }//GEN-LAST:event_btnSimpanActionPerformed


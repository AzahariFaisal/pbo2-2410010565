private void updateInfoBuku() {
    int totalBuku = modelBuku.getRowCount();
    int bukuTersedia = 0;

    for (int i = 0; i < modelBuku.getRowCount(); i++) {
        Buku buku = modelBuku.getBukuAt(i);

        if (buku.getStatus().equalsIgnoreCase("Tersedia")) {
            bukuTersedia++;
        }
    }

    lblInfo.setText(
            "Total Buku: " + totalBuku
            + " | Tersedia: " + bukuTersedia
    );
}

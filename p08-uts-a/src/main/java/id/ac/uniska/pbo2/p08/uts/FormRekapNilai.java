private void tambahData() {
    try {
        String npm = txtNpm.getText().trim();
        String nama = txtNama.getText().trim();

        if (npm.isEmpty() || nama.isEmpty()) {
            JOptionPane.showMessageDialog(this, "NPM dan Nama wajib diisi!");
            return;
        }

        double tugas = Double.parseDouble(txtTugas.getText());
        double uts = Double.parseDouble(txtUts.getText());
        double uas = Double.parseDouble(txtUas.getText());

        if (tugas < 0 || tugas > 100 ||
            uts < 0 || uts > 100 ||
            uas < 0 || uas > 100) {
            JOptionPane.showMessageDialog(this, "Nilai harus 0 sampai 100!");
            return;
        }

        for (int i = 0; i < model.getRowCount(); i++) {
            if (model.getData(i).getNpm().equals(npm)) {
                JOptionPane.showMessageDialog(this, "NPM sudah terdaftar!");
                return;
            }
        }

        model.tambahData(new NilaiMahasiswa(npm, nama, tugas, uts, uas));
        resetForm();

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Nilai harus berupa angka!");
    }
}

private void resetForm() {
    txtNpm.setText("");
    txtNama.setText("");
    txtTugas.setText("");
    txtUts.setText("");
    txtUas.setText("");
    tblNilai.clearSelection();
}

private void hapusData() {
    int baris = tblNilai.getSelectedRow();

    if (baris == -1) {
        JOptionPane.showMessageDialog(this, "Pilih data yang ingin dihapus!");
        return;
    }

    int konfirmasi = JOptionPane.showConfirmDialog(
        this, "Hapus data mahasiswa?", "Konfirmasi",
        JOptionPane.YES_NO_OPTION
    );

    if (konfirmasi == JOptionPane.YES_OPTION) {
        model.hapusData(tblNilai.convertRowIndexToModel(baris));
        resetForm();
    }
}

private void ubahData() {
    int baris = tblNilai.getSelectedRow();

    if (baris == -1) {
        JOptionPane.showMessageDialog(this, "Pilih data yang ingin diubah!");
        return;
    }

    try {
        String npm = txtNpm.getText().trim();
        String nama = txtNama.getText().trim();

        if (npm.isEmpty() || nama.isEmpty()) {
            JOptionPane.showMessageDialog(this, "NPM dan Nama wajib diisi!");
            return;
        }

        double tugas = Double.parseDouble(txtTugas.getText());
        double uts = Double.parseDouble(txtUts.getText());
        double uas = Double.parseDouble(txtUas.getText());

        if (tugas < 0 || tugas > 100 ||
            uts < 0 || uts > 100 ||
            uas < 0 || uas > 100) {
            JOptionPane.showMessageDialog(this, "Nilai harus 0 sampai 100!");
            return;
        }

        int barisModel = tblNilai.convertRowIndexToModel(baris);

        for (int i = 0; i < model.getRowCount(); i++) {
            if (i != barisModel &&
                model.getData(i).getNpm().equals(npm)) {
                JOptionPane.showMessageDialog(this, "NPM sudah digunakan!");
                return;
            }
        }

        model.ubahData(barisModel,
            new NilaiMahasiswa(npm, nama, tugas, uts, uas));

        resetForm();

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Nilai harus berupa angka!");
    }
}


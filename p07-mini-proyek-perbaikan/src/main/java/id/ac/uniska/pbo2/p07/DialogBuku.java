    private void simpan() {
        String kode = isianKode.getText().trim();
        String judul = isianJudul.getText().trim();
        String tahunTeks = isianTahun.getText().trim();
        int tahunSekarang = Year.now().getValue();
        if (kode.isEmpty()) {
            labelPesan.setText("Kode wajib diisi");
            isianKode.requestFocusInWindow();
            return;
        }
        if (judul.isEmpty()) {
            labelPesan.setText("Judul wajib diisi");
            isianJudul.requestFocusInWindow();
            return;
        }
        if (kodeTerpakai.contains(kode.toLowerCase())) {
            labelPesan.setText("Kode " + kode + " sudah dipakai buku lain");
            isianKode.requestFocusInWindow();
            return;
        }
        // Batas 1 sampai 4 digit mencegah angka terlalu panjang sehingga parseInt tidak gagal
        if (!tahunTeks.matches("\\d{1,4}")) {
            labelPesan.setText("Tahun terbit berupa angka " + TAHUN_MINIMAL + " sampai " + tahunSekarang);
            isianTahun.requestFocusInWindow();
            return;
        }
        int tahun = Integer.parseInt(tahunTeks);
        if (tahun < TAHUN_MINIMAL || tahun > tahunSekarang) {
            labelPesan.setText("Tahun terbit berupa angka " + TAHUN_MINIMAL + " sampai " + tahunSekarang);
            isianTahun.requestFocusInWindow();
            return;
        }
        StatusBuku status = (StatusBuku) pilihanStatus.getSelectedItem();
        hasil = new Buku(kode, judul, isianPenulis.getText().trim(), tahun, status);
        dispose();
    }

    /** Menampilkan dialog dan menunggu sampai ditutup. Mengembalikan null jika dibatalkan. */
    public Buku tampilkan() {
        // Pada dialog modal, baris berikut menunggu sampai dialog ditutup
        setVisible(true);
        return hasil;
    }


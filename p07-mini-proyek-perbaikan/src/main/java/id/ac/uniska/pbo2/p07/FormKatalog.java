    private void saring() {
        String kata = isianCari.getText().trim();
        if (kata.isEmpty()) {
            sorter.setRowFilter(null);
        } else {
            // (?i): huruf besar dan kecil dianggap sama; 0, 1, 2: kolom kode, judul, penulis
            sorter.setRowFilter(RowFilter.regexFilter("(?i)" + Pattern.quote(kata), 0, 1, 2));
        }
        perbaruiStatus();
    }

    /**
     * Mengubah nomor baris tampilan menjadi nomor baris model,
     * karena tabel dapat diurutkan dan disaring.
     */
    private int barisTerpilih() {
        int barisTampilan = tabelBuku.getSelectedRow();
        if (barisTampilan < 0) {
            return -1;
        }
        return tabelBuku.convertRowIndexToModel(barisTampilan);
    }

    /** Kode milik semua buku kecuali baris tertentu, dalam huruf kecil. */
    private Set<String> kodeTerpakai(int kecuali) {
        Set<String> hasil = new TreeSet<>();
        for (int i = 0; i < model.getRowCount(); i++) {
            if (i != kecuali) {
                hasil.add(model.get(i).kode().toLowerCase());
            }
        }
        return hasil;
    }

    private void tambah() {
        Buku baru = new DialogBuku(this, "Tambah Buku", null, kodeTerpakai(-1)).tampilkan();
        if (baru != null) {
            model.tambah(baru);
            perbaruiStatus();
        }
    }

    private void ubah() {
        int baris = barisTerpilih();
        if (baris < 0) {
            return;
        }
        Buku hasil = new DialogBuku(this, "Ubah Buku", model.get(baris),
                kodeTerpakai(baris)).tampilkan();
        if (hasil != null) {
            model.ubah(baris, hasil);
            perbaruiStatus(); // status buku bisa berubah sehingga jumlah tersedia ikut berubah
        }
    }

    private void hapus() {
        int baris = barisTerpilih();
        if (baris < 0) {
            return;
        }
        String judul = model.get(baris).judul();
        int jawab = JOptionPane.showConfirmDialog(this, "Hapus buku " + judul + "?",
                "Konfirmasi Hapus", JOptionPane.YES_NO_OPTION, JOptionPane.WARNING_MESSAGE);
        if (jawab == JOptionPane.YES_OPTION) {
            model.hapus(baris);
            perbaruiStatus();
        }
    }

    private void perbaruiTombol() {
        boolean adaPilihan = tabelBuku.getSelectedRow() >= 0;
        tombolUbah.setEnabled(adaPilihan);
        tombolHapus.setEnabled(adaPilihan);
        itemUbah.setEnabled(adaPilihan);
        itemHapus.setEnabled(adaPilihan);
    }

    private void perbaruiStatus() {
        labelStatus.setText("Menampilkan " + tabelBuku.getRowCount()
                + " dari " + model.getRowCount() + " buku | "
                + model.jumlahDenganStatus(StatusBuku.TERSEDIA) + " berstatus tersedia");
    }

